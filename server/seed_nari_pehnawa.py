def kurti_names(style, count=100):
    """Generate {count} realistic kurti product names for a given style."""
    colors = ["Blush Pink","Navy Blue","Ivory","Mustard","Maroon","Teal","Lavender",
              "Off White","Coral","Mint Green","Wine","Emerald","Peach","Orange",
              "Royal Blue","Red","Black","Sage Green","Yellow","Rust","Mauve",
              "Indigo","Champagne","Forest Green","Plum","Sky Blue","Gold","Cream",
              "Burgundy","Olive","Lilac","Turquoise","Rose","Camel","Slate Blue"]
    fabrics = ["Cotton","Rayon","Georgette","Chanderi","Silk Blend","Linen",
               "Crepe","Net","Velvet","Organza","Muslin"]
    occasions = ["Festive","Party","Casual","Wedding","Office","Daily Wear",
                 "Eid Special","Navratri Special","Summer","Winter","Anniversary"]
    trims = ["Embroidered","Printed","Plain","Mirror Work","Gota Patti",
             "Lace Detail","Sequin","Thread Work","Handblock Print","Tie-Dye",
             "Bandhani","Chikankari","Kantha","Phulkari","Zari"]
    names = []
    for i in range(count):
        c = colors[i % len(colors)]
        f = fabrics[i % len(fabrics)]
        o = occasions[i % len(occasions)]
        t = trims[i % len(trims)]
        # Vary naming pattern to keep names unique
        if i % 4 == 0:
            names.append(f"{t} {style} Kurti - {c}")
        elif i % 4 == 1:
            names.append(f"{c} {f} {style} Kurti")
        elif i % 4 == 2:
            names.append(f"{o} {style} Kurti - {c} {f}")
        else:
            names.append(f"{style} Kurti In {c} ({f})")
    return names

